/*
 * Personal Island — clipboard history model and lifecycle.
 * Written for this personal project; no upstream file copied.
 * History is kept in memory only and is never written to disk or sent.
 */

import Combine
import Foundation

enum ClipboardContent: Equatable {
    case text(String)
    case link(URL)
    /// PNG or TIFF data as copied, with its pixel size when known.
    case image(Data, width: Int, height: Int)
    case files([URL])

    var byteCount: Int {
        switch self {
        case .text(let text): text.utf8.count
        case .link(let url): url.absoluteString.utf8.count
        case .image(let data, _, _): data.count
        case .files(let urls): urls.reduce(0) { $0 + $1.path.utf8.count }
        }
    }
}

struct ClipboardItem: Identifiable, Equatable {
    let id: UUID
    let content: ClipboardContent
    var copiedAt: Date
    /// The app in front when the copy was noticed; a hint, not proof.
    var sourceApp: String?
}

/// What a read of the clipboard found.
enum ClipboardRead: Equatable {
    /// Marked concealed or transient (password managers): never read.
    case skipped
    /// Nothing this history keeps (e.g. only private app data).
    case unsupported
    case content(ClipboardContent)
}

/// Whether macOS lets the app read the clipboard without asking.
enum ClipboardAccess: Equatable {
    /// Never asked yet: the first read shows the system's alert once.
    case notAsked
    case allowed
    /// macOS asks before every background read; reading is left off to
    /// avoid repeated alerts until the user chooses Always Allow.
    case asksEachTime
    case denied
}

enum ClipboardStatus: Equatable { case off, recording, paused, needsAccess }

enum ClipboardHistory {
    static let maximumItems = 50
    /// Larger text is cut to this many characters.
    static let maximumTextLength = 100_000
    static let maximumImageBytes = 20 * 1_024 * 1_024
    /// Images beyond this total are dropped, oldest first.
    static let maximumTotalImageBytes = 150 * 1_024 * 1_024
    static let pollInterval: TimeInterval = 0.5

    /// Markers apps put on copies that should not be kept: the nspasteboard.org
    /// conventions used by password managers and clipboard tools, plus
    /// 1Password's and KeeWeb's own. Checking types never reads the content.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "net.antelle.keeweb",
        "com.typeit4me.clipping", "Pasteboard generator type",
    ]

    static func isSkipped(types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// PNG data starts with this signature; anything else is written back as TIFF.
    static func isPNG(_ data: Data) -> Bool {
        data.starts(with: [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    }

    /// A copy that is exactly one web address becomes a link; other text stays text.
    static func content(fromText text: String) -> ClipboardContent {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.contains(where: \.isWhitespace), trimmed.count <= 2_000,
           let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
           ["http", "https"].contains(scheme), url.host?.isEmpty == false {
            return .link(url)
        }
        return .text(text)
    }

    /// Applies one new copy: an identical earlier item moves to the top,
    /// oversized content is cut or refused, and the list stays bounded.
    static func adding(_ content: ClipboardContent, at date: Date, sourceApp: String?,
                       to items: [ClipboardItem], id: UUID = UUID()) -> [ClipboardItem] {
        guard let content = bounded(content) else { return items }
        var result = items
        if let index = result.firstIndex(where: { $0.content == content }) {
            var existing = result.remove(at: index)
            existing.copiedAt = date
            existing.sourceApp = sourceApp ?? existing.sourceApp
            result.insert(existing, at: 0)
        } else {
            result.insert(ClipboardItem(id: id, content: content, copiedAt: date, sourceApp: sourceApp), at: 0)
        }
        if result.count > maximumItems { result.removeLast(result.count - maximumItems) }
        var imageBytes = 0
        result = result.filter { item in
            guard case .image(let data, _, _) = item.content else { return true }
            imageBytes += data.count
            return imageBytes <= maximumTotalImageBytes
        }
        return result
    }

    static func bounded(_ content: ClipboardContent) -> ClipboardContent? {
        switch content {
        case .text(let text):
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            return .text(text.count > maximumTextLength ? String(text.prefix(maximumTextLength)) : text)
        case .link(let url):
            guard let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme) else {
                return .text(url.absoluteString)
            }
            return content
        case .image(let data, _, _):
            return data.isEmpty || data.count > maximumImageBytes ? nil : content
        case .files(let urls):
            let files = urls.filter(\.isFileURL)
            return files.isEmpty ? nil : .files(Array(files.prefix(100)))
        }
    }

    /// Case- and accent-insensitive search over text, links and file names.
    static func matches(_ item: ClipboardItem, query: String) -> Bool {
        let query = query.trimmingCharacters(in: .whitespaces)
        guard !query.isEmpty else { return true }
        let haystack: String
        switch item.content {
        case .text(let text): haystack = text
        case .link(let url): haystack = url.absoluteString
        case .image: haystack = "image picture"
        case .files(let urls): haystack = urls.map(\.lastPathComponent).joined(separator: " ")
        }
        return haystack.range(of: query, options: [.caseInsensitive, .diacriticInsensitive]) != nil
            || (item.sourceApp?.range(of: query, options: [.caseInsensitive, .diacriticInsensitive]) != nil)
    }

    /// The opened view shows at most this many characters; Copy copies all.
    static let displayLimit = 20_000

    /// Full text for the opened view: text as copied, the whole link, or
    /// one file path per line. Very long text is cut for display only.
    static func displayText(_ content: ClipboardContent) -> (text: String, isCut: Bool) {
        let full: String
        switch content {
        case .text(let text): full = text
        case .link(let url): full = url.absoluteString
        case .files(let urls): full = urls.map(\.path).joined(separator: "\n")
        case .image(_, let width, let height): full = width > 0 ? "Image \(width) × \(height)" : "Image"
        }
        guard full.count > displayLimit else { return (full, false) }
        return (String(full.prefix(displayLimit)), true)
    }

    /// "1,234 characters", "3 files", "1.2 MB"; nil for links.
    static func sizeDescription(_ content: ClipboardContent) -> String? {
        switch content {
        case .text(let text):
            let count = text.count
            return count == 1 ? "1 character" : "\(count.formatted()) characters"
        case .link: return nil
        case .files(let urls): return urls.count == 1 ? "1 file" : "\(urls.count) files"
        case .image(let data, _, _):
            return ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file)
        }
    }

    /// One line for the list: collapsed whitespace, bounded length.
    static func preview(_ content: ClipboardContent, limit: Int = 160) -> String {
        switch content {
        case .text(let text):
            let line = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            return line.count > limit ? String(line.prefix(limit)) + "…" : line
        case .link(let url): return url.absoluteString
        case .image(_, let width, let height): return width > 0 ? "Image \(width) × \(height)" : "Image"
        case .files(let urls):
            let first = urls.first?.lastPathComponent ?? ""
            return urls.count > 1 ? "\(first) and \(urls.count - 1) more" : first
        }
    }
}

/// Watches the clipboard while the switch is on and not paused. Platform
/// access is injected so tests never touch the real clipboard.
@MainActor
final class ClipboardController {
    struct Environment {
        /// Reading the change count never shows a privacy alert.
        var changeCount: @MainActor () -> Int
        var access: @MainActor () -> ClipboardAccess
        var read: @MainActor () -> ClipboardRead
        /// Puts content on the clipboard; returns the new change count.
        var write: @MainActor (ClipboardContent) -> Int?
        var frontmostApp: @MainActor () -> String?
        var now: @MainActor () -> Date
        var repeating: @MainActor (TimeInterval, @escaping @MainActor () -> Void) -> AnyCancellable
    }

    private(set) var items: [ClipboardItem] = []
    private(set) var status: ClipboardStatus = .off
    var onChange: (@MainActor () -> Void)?

    private let environment: Environment
    private var timer: AnyCancellable?
    private var lastChangeCount = 0
    private var isPaused = false
    private var generation = 0

    init(environment: Environment) {
        self.environment = environment
    }

    var isActive: Bool { timer != nil }

    /// Starts watching. What is already on the clipboard is not recorded:
    /// only copies made after this point.
    func start() {
        guard timer == nil else { return }
        generation += 1
        let session = generation
        lastChangeCount = environment.changeCount()
        timer = environment.repeating(ClipboardHistory.pollInterval) { [weak self] in
            guard let self, session == self.generation else { return }
            self.poll()
        }
        updateStatus()
    }

    /// Stops watching and forgets the whole history.
    func stop() {
        generation += 1
        timer?.cancel()
        timer = nil
        isPaused = false
        let changed = !items.isEmpty || status != .off
        items = []
        status = .off
        if changed { onChange?() }
    }

    func setPaused(_ paused: Bool) {
        guard timer != nil, paused != isPaused else { return }
        isPaused = paused
        // Copies made while paused are never recorded, even after resuming.
        lastChangeCount = environment.changeCount()
        updateStatus()
    }

    func clear() {
        guard !items.isEmpty else { return }
        items = []
        onChange?()
    }

    func remove(_ id: UUID) {
        guard items.contains(where: { $0.id == id }) else { return }
        items.removeAll { $0.id == id }
        onChange?()
    }

    /// Puts an item back on the clipboard and moves it to the top. The
    /// app's own write is not recorded as a new copy.
    @discardableResult
    func copyBack(_ id: UUID) -> Bool {
        guard let item = items.first(where: { $0.id == id }),
              let count = environment.write(item.content) else { return false }
        lastChangeCount = count
        items = ClipboardHistory.adding(item.content, at: environment.now(), sourceApp: item.sourceApp, to: items)
        onChange?()
        return true
    }

    private func poll() {
        updateStatus()
        let count = environment.changeCount()
        guard count != lastChangeCount else { return }
        guard !isPaused, status == .recording else {
            // Not readable now; never catch up on it later.
            lastChangeCount = count
            return
        }
        lastChangeCount = count
        guard case .content(let content) = environment.read() else { return }
        let next = ClipboardHistory.adding(content, at: environment.now(), sourceApp: environment.frontmostApp(), to: items)
        guard next != items else { return }
        items = next
        onChange?()
    }

    private func updateStatus() {
        let next: ClipboardStatus
        if timer == nil {
            next = .off
        } else if isPaused {
            next = .paused
        } else {
            switch environment.access() {
            case .allowed, .notAsked: next = .recording
            case .asksEachTime, .denied: next = .needsAccess
            }
        }
        guard next != status else { return }
        status = next
        onChange?()
    }
}
